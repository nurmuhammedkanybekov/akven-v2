/**
 * Writes the demo seeds that only the demo profile loads:
 *   V25__seed_collection_2.sql                the second collection (scripts/collection-2.mjs)
 *   V28__seed_classics_and_colour_pictures.sql the classic line (scripts/collection-3.mjs), and for every sock a
 *                                              picture per colour, so choosing a colour shows that colour
 * Deterministic, so running it again without changing the lists gives the same files. V25 has been applied by existing
 * installations: its output must never change (Flyway checks it), which is why it is written first, from the same
 * starting set of SKUs as before.
 * Run: npm run seed
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { SOCK_COLOURS as C } from "../src/brand/sockDrawing.ts";
import { COLLECTION_2 } from "./collection-2.mjs";
import { COLLECTION_3 } from "./collection-3.mjs";
import { LEGACY_COLOURS, collectionColours, colourName, colourSlug } from "./colours.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const seedDir = path.join(root, "backend/src/main/resources/db/seed");
const out = path.join(seedDir, "V25__seed_collection_2.sql");
const out28 = path.join(seedDir, "V28__seed_classics_and_colour_pictures.sql");

const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const money = (n) => n.toFixed(2);

// SKUs already used by the earlier seeds, so a new code never collides with one.
const taken = new Set();
for (const f of fs.readdirSync(seedDir)) {
  if (f === path.basename(out) || f === path.basename(out28)) continue;
  for (const m of fs.readFileSync(path.join(seedDir, f), "utf8").matchAll(/\('([A-Z0-9]+(?:-[A-Z0-9]+)+)'/g)) taken.add(m[1]);
}
const prefixes = new Map();
function prefix(slug) {
  if (prefixes.has(slug)) return prefixes.get(slug);
  const words = slug.split("-");
  let p = words.map((w) => w[0]).join("").toUpperCase().slice(0, 4);
  if (p.length < 3) p = slug.replace(/-/g, "").slice(0, 3).toUpperCase();
  const used = new Set(prefixes.values());
  const clash = (cand) => used.has(cand) || [...taken].some((s) => s.startsWith(cand + "-"));
  let n = 2;
  const base = p;
  while (clash(p)) p = base + n++;
  prefixes.set(slug, p);
  return p;
}

const socks = COLLECTION_2.filter((p) => p.sock);
const boxes = COLLECTION_2.filter((p) => p.box);

const productRow = (p) =>
  `    (${q(p.slug)}, ${q(p.name)}, ${q(p.category)}, ${q(p.section)}, ${q(p.cut)}, ${q(p.collection)},\n     ${q(p.description)},\n     ${q(p.fabric)}, ${q(p.quality)})`;
const boxRow = (p) =>
  `    (${q(p.slug)}, ${q(p.name)}, 'BUNDLES', ${q(p.collection)},\n     ${q(p.description)},\n     ${q(p.fabric)}, ${q(p.quality)}, 'See each pair.', 'Korea')`;

const variantRows = [];
for (const p of COLLECTION_2) {
  const warm = p.section === "thermal" || p.section === "home";
  for (const [size, colour, pack, stock, incoming = 0, eta = null] of p.variants) {
    const sizeCode = size ? size.replace(/\s+/g, "").toUpperCase().replace("ONESIZE", "OS") : "MIX";
    const sku = `${prefix(p.slug)}-${colour.slice(0, 3).toUpperCase()}-${sizeCode}-${pack}`;
    if (taken.has(sku)) throw new Error(`SKU ${sku} is used twice`);
    taken.add(sku);
    const price = p.price;
    const cost = Math.round(price * 0.43 * 100) / 100;
    const floor = pack > 1 ? 18 : 15;
    const casePairs = p.box ? null : warm ? 200 : 240;
    variantRows.push(`    (${q(sku)}, ${q(p.slug)}, ${q(size)}, ${q(p.box ? "Mixed" : colourName(colour))}, ${q(C[colour].toUpperCase())}, ${pack}, ${money(price)}, ${money(cost)}, ${money(floor)}, ${stock}, ${incoming}, ${eta ?? "null"}, ${casePairs ?? "null"})`);
  }
}
// The first row carries the column types for the whole values list.
variantRows[0] = variantRows[0].replace(/, (\d+|null), (\d+|null)\)$/, (_, eta, cp) => `, ${eta}::int, ${cp}::int)`);

const sql = `-- Demo-only: the second collection, generated by frontend/scripts/generate-seed.mjs from scripts/collection-2.mjs.
-- Do not edit by hand: change the list and run \`npm run seed\` (and \`npm run art\` for the images).
-- Checks, houndstooth, fair isle and cable knit; the Ala-Too, shyrdak and Issyk-Kul designs; a garden line; Seoul
-- street socks; kittens, bunnies, paws and football for children; and boxes for Valentine's Day, a toi, a new baby
-- and Teacher's Day. Names, prices and stock are examples; the owners replace them from the admin.

insert into product (slug, name, category, section_id, cut_id, collection, description, fabric_composition, quality, care, origin)
select v.slug, v.name, v.category, s.id, c.id, v.collection, v.description, v.fabric, v.quality,
       'Machine wash at 30 °C inside out. Do not tumble dry hot. Do not bleach.', 'Korea'
from (values
${socks.map(productRow).join(",\n")}
) as v(slug, name, category, section, cut, collection, description, fabric, quality)
join catalog_term s on s.kind = 'SECTION' and s.slug = v.section
join catalog_term c on c.kind = 'CUT' and c.slug = v.cut;

insert into product (slug, name, category, collection, description, fabric_composition, quality, care, origin) values
${boxes.map(boxRow).join(",\n")};

insert into variant (product_id, sku, size, color, color_hex, pack_size, price, cost_price, margin_floor_pct, stock_qty, incoming_qty, restock_eta, case_pairs)
select p.id, v.sku, v.size, v.color, v.hex, v.pack, v.price, v.cost, v.floor, v.stock, v.incoming,
       case when v.eta_days is null then null else current_date + v.eta_days end, v.case_pairs
from (values
${variantRows.join(",\n")}
) as v(sku, slug, size, color, hex, pack, price, cost, floor, stock, incoming, eta_days, case_pairs)
join product p on p.slug = v.slug;

-- Two drawn images for every new product: the sock on its own, and the pair (or the open box).
insert into product_image (product_id, url, alt, position)
select p.id, '/media/products/' || p.slug || '-1.svg', p.name || ' - AKVEN', 0
  from product p
 where not exists (select 1 from product_image i where i.product_id = p.id and i.position = 0);

insert into product_image (product_id, url, alt, position)
select p.id, '/media/products/' || p.slug || '-2.svg', p.name || ', the pair - AKVEN', 1
  from product p
 where not exists (select 1 from product_image i where i.product_id = p.id and i.position = 1);
`;
fs.writeFileSync(out, sql);
console.log(`wrote ${COLLECTION_2.length} products and ${variantRows.length} variants to ${path.relative(root, out)}`);

// ---- V28: the classic line, and a picture per colour for every sock ----------------------------------------------

const classicRows = [];
for (const p of COLLECTION_3) {
  const warm = p.section === "thermal" || p.section === "home";
  for (const [size, colour, pack, stock, incoming = 0, eta = null] of p.variants) {
    const sku = `${prefix(p.slug)}-${colour.slice(0, 3).toUpperCase()}-${size.replace(/\s+/g, "").toUpperCase()}-${pack}`;
    if (taken.has(sku)) throw new Error(`SKU ${sku} is used twice`);
    taken.add(sku);
    const price = p.packPrices?.[pack] ?? Math.round(p.price * pack * (pack > 1 ? 0.88 : 1) * 2) / 2;
    const cost = Math.round(price * 0.45 * 100) / 100;
    classicRows.push(`    (${q(sku)}, ${q(p.slug)}, ${q(size)}, ${q(colourName(colour))}, ${q(C[colour].toUpperCase())}, ${pack}, ${money(price)}, ${money(cost)}, ${money(pack > 1 ? 18 : 15)}, ${stock}, ${incoming}, ${eta ?? "null"}, ${warm ? 200 : 240})`);
  }
}
classicRows[0] = classicRows[0].replace(/, (\d+|null), (\d+|null)\)$/, (_, eta, cp) => `, ${eta}::int, ${cp}::int)`);

// Pictures per colour: the sock and the pair, after the product's own two (positions 0 and 1).
const pictureRows = [];
const names = Object.fromEntries([...COLLECTION_2, ...COLLECTION_3].map((p) => [p.slug, p.name]));
const colours = { ...LEGACY_COLOURS };
for (const p of [...COLLECTION_2, ...COLLECTION_3]) if (!p.box) colours[p.slug] = collectionColours(p);
for (const [slug, list] of Object.entries(colours).sort(([a], [b]) => a.localeCompare(b))) {
  list.forEach(([name], i) => {
    const file = `/media/products/${slug}--${colourSlug(name)}`;
    pictureRows.push(`    (${q(slug)}, ${q(name)}, ${q(`${file}-1.svg`)}, ${q(`${file}-2.svg`)}, ${2 + i * 2})`);
  });
}

const sql28 = `-- Demo-only: the classic line, and a picture for every colour of every sock. Generated by
-- frontend/scripts/generate-seed.mjs from scripts/collection-3.mjs and the other collections; do not edit by hand
-- (change the lists and run \`npm run seed\`, and \`npm run art\` for the pictures).
-- Plain and ribbed socks in every height, for men, women and children, in the colours bought by the dozen, as single
-- pairs and packs. Names, prices and stock are examples; the owners replace them from the admin.

insert into product (slug, name, category, section_id, cut_id, collection, description, fabric_composition, quality, care, origin)
select v.slug, v.name, v.category, s.id, c.id, v.collection, v.description, v.fabric, v.quality,
       'Machine wash at 30 °C inside out. Do not tumble dry hot. Do not bleach.', 'Korea'
from (values
${COLLECTION_3.map(productRow).join(",\n")}
) as v(slug, name, category, section, cut, collection, description, fabric, quality)
join catalog_term s on s.kind = 'SECTION' and s.slug = v.section
join catalog_term c on c.kind = 'CUT' and c.slug = v.cut;

insert into variant (product_id, sku, size, color, color_hex, pack_size, price, cost_price, margin_floor_pct, stock_qty, incoming_qty, restock_eta, case_pairs)
select p.id, v.sku, v.size, v.color, v.hex, v.pack, v.price, v.cost, v.floor, v.stock, v.incoming,
       case when v.eta_days is null then null else current_date + v.eta_days end, v.case_pairs
from (values
${classicRows.join(",\n")}
) as v(sku, slug, size, color, hex, pack, price, cost, floor, stock, incoming, eta_days, case_pairs)
join product p on p.slug = v.slug;

-- The classics' own two pictures, drawn in their first colour.
insert into product_image (product_id, url, alt, position)
select p.id, '/media/products/' || p.slug || '-1.svg', p.name || ' - AKVEN', 0
  from product p
 where not exists (select 1 from product_image i where i.product_id = p.id and i.position = 0);

insert into product_image (product_id, url, alt, position)
select p.id, '/media/products/' || p.slug || '-2.svg', p.name || ', the pair - AKVEN', 1
  from product p
 where not exists (select 1 from product_image i where i.product_id = p.id and i.position = 1);

-- A picture of each colour: choosing it on the product page or in quick view shows it.
insert into product_image (product_id, url, alt, position, color)
select p.id, x.url, p.name || ', ' || lower(x.color) || x.what || ' - AKVEN', x.pos, x.color
from (values
${pictureRows.join(",\n")}
) as v(slug, color, url1, url2, pos)
cross join lateral (values (v.url1, v.pos, v.color, ''), (v.url2, v.pos + 1, v.color, ', the pair')) as x(url, pos, color, what)
join product p on p.slug = v.slug
where not exists (select 1 from product_image i where i.product_id = p.id and i.position = x.pos);
`;
fs.writeFileSync(out28, sql28);
console.log(`wrote ${COLLECTION_3.length} classics, ${classicRows.length} variants and ${pictureRows.length * 2} colour pictures to ${path.relative(root, out28)}`);
